"""Export real artefacts from the recorded run into video/data.js, so the film shows what actually happened:
Synapse's discovered endpoints, the tool calls per turn, Barnaby's real lines, the real Build diff, test result,
and Theo's git history.

  .venv/Scripts/python scripts/dev/export_film_data.py
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
run = json.loads((ROOT / "ui" / "fixtures" / "demo-run.json").read_text(encoding="utf-8"))
events = run["events"]
shop = run["state_before"]["systems"][0]

turns: dict[int, dict] = {}
cur = None
for e in events:
    d = e["data"]
    if e["type"] == "turn.start":
        cur = turns.setdefault(d["turn"], {"ask": d["text"], "calls": [], "said": []})
    elif cur is None:
        continue
    elif e["type"] == "tool.call":
        cur["calls"].append({"system": d.get("system"), "tool": d["tool"], "input": d.get("input")})
    elif e["type"] == "say" and not d.get("final"):
        cur["said"].append(d["text"])

diff = next((e["data"].get("diff") for e in events if e["type"] == "approval.requested" and e["data"].get("tier") == "build"), "")
tested = next((e["data"]["result"] for e in events if e["type"] == "growth.build.tested"), "")
built = next((e["data"] for e in events if e["type"] == "growth.build.done"), {})
repo = ROOT / ".demo" / "spokes-and-sprockets"
log = subprocess.run(["git", "log", "--format=%ad|%an|%s", "--date=short"], cwd=repo, capture_output=True, text=True).stdout
data = {
    "endpoints": [{"key": e["key"], "tool": e["tool"], "read_only": e["read_only"], "description": e["description"]} for e in shop["endpoints"]],
    "starter": shop["exposed"],
    "turns": [turns[k] for k in sorted(turns)],
    "build": {"diff": diff, "tested": tested, "endpoints": built.get("endpoints", []), "tools": built.get("tools", [])},
    "gitlog": [dict(zip(["date", "author", "subject"], line.split("|", 2))) for line in log.strip().splitlines()],
}
out = ROOT / "video" / "data.js"
out.write_text("/* Generated by scripts/dev/export_film_data.py from a real recorded run. Do not edit by hand. */\n"
               "window.DATA = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print(f"{out}: {len(data['endpoints'])} endpoints, {len(data['turns'])} turns, diff {len(diff)} chars, git log {len(data['gitlog'])} commits")
sys.exit(0)
