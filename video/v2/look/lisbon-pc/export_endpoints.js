/* Real Synapse scan results for the Lisbon beat -> endpoints.js (checked in, so the page needs nothing else).
 *
 *   node video/v2/look/lisbon-pc/export_endpoints.js
 *
 * Reads what `synapse build --auto --local` (CLI 0.1.9) actually wrote for the two montage repos:
 *   .demo/montage/<repo>/synapse_auto_server.py          one @mcp.tool per endpoint: tool name, method, path
 *   .demo/montage/<repo>/.synapse/surface_cache.json     language, framework, package import root
 *   .demo/montage/<repo>/.synapse/discover/*.jsonl       session id, endpoint count, scan timings
 * Nothing is invented: if a repo is missing, its entry is left out and the page shows the count alone. */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../../../..');
const MONTAGE = path.join(ROOT, '.demo/montage');
const OUT = path.join(__dirname, 'endpoints.js');

function read(repo) {
  const dir = path.join(MONTAGE, repo);
  const server = path.join(dir, 'synapse_auto_server.py');
  if (!fs.existsSync(server)) return null;
  const src = fs.readFileSync(server, 'utf8');
  const list = [];
  // each tool: @mcp.tool(name="x", ...)\ndef x(...):\n    url = f"{...}/path"\n ... requests.<method>(
  const re = /@mcp\.tool\(name="([^"]+)"[\s\S]*?url = f"\{os\.environ\["ENDPOINT_BASE_URL"\]\}([^"]*)"[\s\S]*?requests\.(get|post|put|patch|delete)\(/g;
  let m;
  while ((m = re.exec(src))) list.push({ m: m[3].toUpperCase(), p: m[2] || '/', tool: m[1] });
  const cache = JSON.parse(fs.readFileSync(path.join(dir, '.synapse/surface_cache.json'), 'utf8'));
  const disc = path.join(dir, '.synapse/discover');
  let session = null, count = list.length, ms = null, cli = null;
  for (const f of fs.existsSync(disc) ? fs.readdirSync(disc) : []) {
    let open = null;
    for (const line of fs.readFileSync(path.join(disc, f), 'utf8').split(/\r?\n/)) {
      if (!line.trim()) continue;
      const ev = JSON.parse(line);
      if (ev.type === 'session_open') { open = ev; session = ev.session_id; cli = ev.cli_version; }
      if (ev.type === 'session_done') { count = ev.endpoints_count; if (open) ms = ev.at - open.started_at; }
    }
  }
  return {
    repo, count, session, cli, scanMs: ms,
    language: cache.language, framework: cache.framework, module: cache.package_import_root,
    linesScanned: cache.lines_scanned, endpoints: list,
  };
}

const data = {};
for (const repo of ['quorum', 'comfyui']) {
  const r = read(repo);
  if (r) data[repo] = r;
  console.log(repo, r ? `${r.endpoints.length} tools parsed, session says ${r.count}` : 'missing');
}
fs.writeFileSync(OUT, `/* GENERATED by export_endpoints.js from the real Synapse scans in .demo/montage (do not edit). */\n` +
  `window.LX_ENDPOINTS = ${JSON.stringify(data, null, 1)};\n`);
console.log(OUT);
